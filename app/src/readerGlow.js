// Цветное пятно модуля — одно и то же на карточке (SelectPage) и в читалке
// (ReaderPage). Переход «карточка → весь экран» везёт пятно из угла карточки
// туда, где читалка держит его при прокрутке 0, поэтому обе стороны берут
// числа отсюда: поменяешь одно место — стык не разъедется.

// На карточке: круг 240px, выступает за правый верхний угол на 90/100px.
export const CARD_GLOW = { size: 240, right: -90, top: -100 };

// В читалке, в координатах экрана при прокрутке 0: правый верхний угол
// пятна на 290px правее и 220px выше угла экрана — видна только его часть.
export const READER_GLOW = { top: -220, outRight: 290 };

// Размер в читалке: увеличенное пятно карточки, на телефоне не шире экрана.
export const readerGlowSize = () => Math.min(528, window.innerWidth * 1.1);
export const readerGlowScale = () => readerGlowSize() / CARD_GLOW.size;
